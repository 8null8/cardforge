#!/usr/bin/env python3
"""
Builds the list collector as a browser extension for Chrome (and Edge) and Firefox (desktop and Android):

  python3 tools/build-extension.py

-> dist/cardforge-collector-chrome-<version>.zip and dist/cardforge-collector-firefox-<version>.zip, ready to upload
to the Chrome Web Store / addons.mozilla.org (see extension/PUBLISHING.md), plus the unpacked folders next to them.

The extension IS the userscript 5etools-card-list.user.js: its two storage functions (GM_getValue / GM_setValue)
are backed by the extension's own storage, nothing else changes. The version is the userscript's @version, so bump
that for every change and rebuild.
"""
import json
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "5etools-card-list.user.js"
EXT = ROOT / "extension"
DIST = ROOT / "dist"

FIREFOX_ID = "card-forge-collector@arcvein.org"   # never change this once the add-on is published on AMO
MATCHES = ["https://5e.tools/*", "https://www.5e.tools/*"]

WRAPPER = """\
// Card Forge list collector, browser extension edition. Generated by tools/build-extension.py from
// 5etools-card-list.user.js: edit that file, not this one.
// The userscript's GM_getValue / GM_setValue are backed by the extension's storage (kept in step across tabs).
(async () => {
  const api = globalThis.browser || globalThis.chrome;
  const cache = await api.storage.local.get(null);
  api.storage.onChanged.addListener((changes, area) => {
    if (area !== "local") return;
    for (const [k, c] of Object.entries(changes)) { if ("newValue" in c) cache[k] = c.newValue; else delete cache[k]; }
  });
  const GM_getValue = (k, d) => (Object.prototype.hasOwnProperty.call(cache, k) ? cache[k] : d);
  const GM_setValue = (k, v) => { cache[k] = v; api.storage.local.set({ [k]: v }); };

%s
})();
"""


def manifest(browser, version, description):
    m = {
        "manifest_version": 3,
        "name": "Card Forge list collector",
        "short_name": "Card Forge",
        "version": version,
        "description": description,
        "homepage_url": "https://github.com/8null8/cardforge",
        "icons": {str(n): f"icons/icon-{n}.png" for n in (16, 32, 48, 128)},
        "permissions": ["storage"],
        "content_scripts": [{"matches": MATCHES, "js": ["content.js"], "run_at": "document_idle"}],
    }
    if browser == "firefox":
        m["browser_specific_settings"] = {
            "gecko": {"id": FIREFOX_ID, "strict_min_version": "140.0",
                      # the list only ever leaves the browser when you press Send, inside the address's #fragment
                      "data_collection_permissions": {"required": ["none"]}},
            "gecko_android": {"strict_min_version": "142.0"},
        }
    return m


def main():
    src = SRC.read_text(encoding="utf-8")
    m = re.search(r"^// @version\s+(\S+)", src, re.M)
    if not m or not re.fullmatch(r"\d+(\.\d+){0,3}", m.group(1)):
        sys.exit("5etools-card-list.user.js needs an @version made of 1-4 numbers, e.g. 1.7")
    version = m.group(1)
    d = re.search(r"^// @description\s+(.+)$", src, re.M)
    description = "Collect spells, creatures, items and class features on 5e.tools, then send the list to Card Forge to make printable cards."
    if d and len(d.group(1)) <= 132:
        description = d.group(1).strip()
    for name in ("GM_getValue", "GM_setValue"):
        if name not in src:
            print(f"note: the userscript no longer uses {name}")
    used = set(re.findall(r"\bGM_\w+|\bGM\.\w+|\bunsafeWindow\b", src)) - {"GM_getValue", "GM_setValue"}
    if used:
        sys.exit(f"the userscript uses {', '.join(sorted(used))}: add it to the wrapper in tools/build-extension.py first")
    content = WRAPPER % src.rstrip()

    DIST.mkdir(exist_ok=True)
    for browser in ("chrome", "firefox"):
        out = DIST / f"cardforge-collector-{browser}"
        shutil.rmtree(out, ignore_errors=True)
        (out / "icons").mkdir(parents=True)
        (out / "manifest.json").write_text(json.dumps(manifest(browser, version, description), indent=2) + "\n", encoding="utf-8")
        (out / "content.js").write_text(content, encoding="utf-8")
        for p in (EXT / "icons").glob("icon-*.png"):
            shutil.copy(p, out / "icons" / p.name)
        z = DIST / f"cardforge-collector-{browser}-{version}.zip"
        with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
            for p in sorted(out.rglob("*")):
                if p.is_file():
                    zf.write(p, p.relative_to(out).as_posix())   # manifest.json at the top of the zip
        print(f"Built {z.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
